# 2. RAG SERVICE SCHEMAS
# =====================================================================

class AskRequest(BaseModel):
    """Request payload for RAG policy question answering."""
    question: str = Field(
        ...,
        min_length=1,
        max_length=1000,
        description="The enterprise question to answer.",
        examples=["What is the meal per diem allowance for domestic travel?"],
    )

    @field_validator("question")
    @classmethod
    def validate_non_whitespace(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Question cannot be empty or whitespace only.")
        return stripped


class CitationSource(BaseModel):
    """Verifiable source citation extracted from retrieved chunk metadata."""
    rank: int = Field(..., description="Retrieval ranking position")
    title: str = Field(..., description="Document title")
    source_file: str = Field(..., description="Source file path")
    chunk_uid: str = Field(..., description="Unique chunk identifier")
    rerank_score: float = Field(..., description="Cross-encoder rerank score")
    snippet: str = Field(..., description="Excerpt of the retrieved chunk content")


class AskResponse(BaseModel):
    """Grounded RAG answer and deterministic source citations."""
    question: str = Field(..., description="The original sanitized query")
    answer: str = Field(..., description="Grounded answer generated by LLM")
    is_refusal: bool = Field(..., description="True if question was refused due to missing evidence")
    sources: list[CitationSource] = Field(
        default_factory=list,
        description="Deterministic source citations supporting the answer",
    )



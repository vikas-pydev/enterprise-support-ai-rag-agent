# 7. HUMAN-IN-THE-LOOP APPROVAL SCHEMAS (PHASE 7 TASK 4)
# =====================================================================

class ApprovalDecisionRequest(BaseModel):
    """Payload for submitting a human operator decision for an approval-protected workflow."""
    decision: str = Field(
        ...,
        description="Explicit human decision: 'approve' or 'reject'.",
        examples=["approve", "reject"],
    )
    session_id: str | None = Field(
        default=None,
        description="Optional session identifier to verify approval ownership against.",
    )
    notes: str | None = Field(default=None, description="Optional operator justification or review notes.")

    @field_validator("decision")
    @classmethod
    def validate_decision(cls, v: str) -> str:
        clean = v.strip().lower()
        if clean not in ("approve", "reject"):
            raise ValueError("Decision must be explicitly 'approve' or 'reject'.")
        return clean


class ApprovalDecisionResponse(BaseModel):
    """Response returned after processing a human approval decision."""
    approval_id: str = Field(..., description="Unique approval request identifier")
    decision: str = Field(..., description="Submitted decision ('approve' or 'reject')")
    status: str = Field(..., description="Workflow outcome status ('completed', 'rejected', 'error')")
    answer: str = Field(..., description="Synthesized answer or safe termination message")
    duration_ms: float = Field(default=0.0, description="Total execution duration in milliseconds")
    trace: AgentExecutionTraceResponse | None = Field(
        default=None,
        description="Structured execution trace metadata",
    )



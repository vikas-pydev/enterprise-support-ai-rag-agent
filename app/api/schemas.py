class AgentChatRequest(BaseModel):
    """Request payload for multi-turn agent conversation."""
    session_id: str = Field(
        ...,
        min_length=1,
        max_length=128,
        description="Unique conversation session identifier.",
        examples=["session-emp-1001"],
    )
    message: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="User question or follow-up inquiry.",
        examples=["What is the employee information for E1001?"],
    )

    @field_validator("session_id")
    @classmethod
    def validate_session_id(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("session_id cannot be empty or whitespace only.")
        return stripped

    @field_validator("message")
    @classmethod
    def validate_message(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("message cannot be empty or whitespace only.")
        return stripped


class AgentStepResponse(BaseModel):
    """Represents a single tool invocation step within an agent execution."""
    step_number: int = Field(default=1, description="Sequential step position (1-indexed)")
    tool_name: str = Field(..., description="Name of the invoked LangChain tool")
    tool_args: dict[str, Any] = Field(default_factory=dict, description="Validated tool arguments")
    tool_result: dict[str, Any] = Field(default_factory=dict, description="Structured tool execution result")
    status: str = Field(default="success", description="Step execution status: success, error, or rejected_duplicate")
    duration_ms: float = Field(default=0.0, description="Tool execution duration in milliseconds")
    error: str | None = Field(default=None, description="Sanitized error message if applicable")


class AgentExecutionTraceResponse(BaseModel):
    """Execution trace metadata summarizing agent lifecycle for observability."""
    session_id: str | None = Field(default=None, description="Session identifier")
    total_steps: int = Field(default=0, description="Total steps executed")
    total_duration_ms: float = Field(default=0.0, description="Total agent execution duration in milliseconds")
    used_rag: bool = Field(default=False, description="Whether RAG policy knowledge was retrieved")
    status: str = Field(default="completed", description="Final run status")
    tools_invoked: list[str] = Field(default_factory=list, description="Ordered list of tool names called")


class AgentChatResponse(BaseModel):
    """Standardized response from the multi-turn conversational agent."""
    session_id: str = Field(..., description="Active session identifier")
    query: str = Field(..., description="User query submitted for this turn")
    answer: str = Field(..., description="Final synthesized answer from the agent")
    status: str = Field(..., description="Execution status: completed, max_steps_reached, or error")
    steps: list[AgentStepResponse] = Field(
        default_factory=list,
        description="Sequential list of tool execution steps taken by the agent",
    )
    total_steps: int = Field(default=0, description="Total number of tool calls executed")
    duration_ms: float = Field(default=0.0, description="Total agent run execution duration in milliseconds")
    used_rag: bool = Field(default=False, description="Indicates whether RAG policy retrieval was invoked")
    citations: list[CitationSource] = Field(
        default_factory=list,
        description="Deterministic source citations supporting policy answers",
    )
    trace: AgentExecutionTraceResponse | None = Field(
        default=None,
        description="Structured execution trace metadata",
    )


class SessionClearResponse(BaseModel):
    """Response returned when a conversational session is cleared or deleted."""
    session_id: str = Field(..., description="Identifier of the modified session")
    status: str = Field(default="cleared", description="Operation status")
    message: str = Field(..., description="Confirmation message")



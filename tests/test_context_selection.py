def test_empty_and_unanswerable():
    # Empty query or candidates
    selected, stats = select_and_compress_context([])
    assert selected == []
    assert stats.initial_chunks == 0
    assert stats.final_chunks == 0

    # Unanswerable query through retriever
    unans_results = retrieve("What is the company policy for pet insurance?", config=MEDIUM_CONFIG)
    assert unans_results == [], f"Expected empty results for unanswerable query, got {unans_results}"
    print("[PASS] test_empty_and_unanswerable passed.")


def test_retriever_with_config_presets():
    query = "How many annual leave days do employees receive?"

    # Small config
    res_small, stats_small = retrieve(query, config=SMALL_CONFIG, return_stats=True)
    assert len(res_small) <= SMALL_CONFIG.final_context_k
    assert stats_small.final_chars <= SMALL_CONFIG.max_context_chars

    # Medium config (Default)
    res_med, stats_med = retrieve(query, config=MEDIUM_CONFIG, return_stats=True)
    assert len(res_med) <= MEDIUM_CONFIG.final_context_k
    assert stats_med.final_chars <= MEDIUM_CONFIG.max_context_chars
    assert res_med[0][2]["document_id"] == "leave_policy"

    # Large config
    res_large, stats_large = retrieve(query, config=LARGE_CONFIG, return_stats=True)
    assert len(res_large) <= LARGE_CONFIG.final_context_k

    print("[PASS] test_retriever_with_config_presets passed.")



def test_jaccard_similarity():
    tokens1 = _tokenize_for_similarity("Employee receives 24 annual leave days.")
    tokens2 = _tokenize_for_similarity("Employee receives 24 days of annual leave.")
    sim = calculate_jaccard_similarity(tokens1, tokens2)
    assert sim > 0.6, f"Expected high similarity, got {sim}"

    tokens3 = _tokenize_for_similarity("Meal allowance for domestic travel is $75.")
    sim2 = calculate_jaccard_similarity(tokens1, tokens3)
    assert sim2 == 0.0, f"Expected zero similarity, got {sim2}"
    print("[PASS] test_jaccard_similarity passed.")


def test_exact_duplicate_removal():
    candidates = [
        ("Annual leave allows 24 days.", 9.5, {"chunk_uid": "doc1_chunk_0", "title": "Leave"}),
        ("Annual leave allows 24 days.", 9.2, {"chunk_uid": "doc1_chunk_0", "title": "Leave"}),  # duplicate uid
        ("Different chunk content.", 8.0, {"chunk_uid": "doc1_chunk_1", "title": "Leave"}),
        ("Annual leave allows 24 days.", 7.5, {"chunk_uid": "doc1_chunk_2", "title": "Leave"}),  # duplicate text
    ]

    selected, stats = select_and_compress_context(candidates, max_chunks=5, max_chars=1000)
    assert len(selected) == 2, f"Expected 2 unique chunks, got {len(selected)}"
    assert stats.exact_duplicates_removed == 2, f"Expected 2 duplicates removed, got {stats.exact_duplicates_removed}"
    assert selected[0][2]["chunk_uid"] == "doc1_chunk_0"
    assert selected[1][2]["chunk_uid"] == "doc1_chunk_1"
    print("[PASS] test_exact_duplicate_removal passed.")


def test_redundancy_reduction():
    # Chunks generated by sliding window overlap where chunk 1 and chunk 2 share 85% words
    chunk1 = "Annual leave policy: Employees receive 24 days of annual leave per calendar year. Approval must be obtained from your manager."
    chunk2 = "Employees receive 24 days of annual leave per calendar year. Approval must be obtained from your direct reporting manager."
    chunk3 = "Emergency leave is granted for unexpected personal circumstances requiring immediate absence."

    candidates = [
        (chunk1, 9.5, {"chunk_uid": "leave_0", "title": "Leave"}),
        (chunk2, 9.1, {"chunk_uid": "leave_1", "title": "Leave"}),  # redundant with chunk1
        (chunk3, 8.2, {"chunk_uid": "leave_2", "title": "Leave"}),
    ]

    selected, stats = select_and_compress_context(
        candidates,
        max_chunks=5,
        max_chars=2000,
        redundancy_threshold=0.70,
    )
    assert len(selected) == 2, f"Expected 2 chunks after redundancy filter, got {len(selected)}"
    assert stats.redundant_chunks_removed == 1, f"Expected 1 redundant chunk removed, got {stats.redundant_chunks_removed}"
    assert selected[0][2]["chunk_uid"] == "leave_0"
    assert selected[1][2]["chunk_uid"] == "leave_2"
    print("[PASS] test_redundancy_reduction passed.")


def test_context_budget_enforcement():
    # Distinct topics so they are not filtered by Jaccard redundancy
    topics = [
        "Annual leave allocation grants 24 paid days per calendar year for personal time.",
        "Meal allowances on business trips allow $75 daily reimbursement for food expenses.",
        "Health insurance coverage begins on the first calendar day of full-time employment.",
        "Retirement plans offer 401k matching up to four percent of base annual salary.",
        "Core collaboration hours require presence between 10 AM and 4 PM on weekdays.",
        "Fitness stipends provide $500 yearly assistance for gym and wellness memberships.",
        "Emergency leaves cover unexpected personal situations requiring immediate attention.",
        "Flight bookings exceeding six hours qualify for business class cabin travel.",
        "Carry-forward vacation days expire on March 31 of the subsequent calendar year.",
        "Tardiness exceeding 30 minutes must be reported promptly to direct supervisors.",
    ]
    candidates = [
        (topic, 10.0 - i, {"chunk_uid": f"topic_{i}"})
        for i, topic in enumerate(topics)
    ]

    selected_k2, _ = select_and_compress_context(candidates, max_chunks=2, max_chars=5000)
    assert len(selected_k2) == 2, f"Expected 2 chunks, got {len(selected_k2)}"

    selected_k5, _ = select_and_compress_context(candidates, max_chunks=5, max_chars=5000)
    assert len(selected_k5) == 5, f"Expected 5 chunks, got {len(selected_k5)}"

    # Test character budget cap (each topic is ~80 chars; 150 chars fits at most 2 topics)
    selected_chars, stats = select_and_compress_context(candidates, max_chunks=10, max_chars=150)
    total_chars = sum(len(d.strip()) for d, _, _ in selected_chars)
    assert total_chars <= 150, f"Expected <= 150 chars, got {total_chars}"
    assert len(selected_chars) < len(candidates)
    assert stats.budget_exceeded_chunks_removed > 0
    print("[PASS] test_context_budget_enforcement passed.")



/**
 * Strongly typed TypeScript interfaces mirroring backend Pydantic models in `app/api/schemas.py`.
 */

// =====================================================================
// 1. HEALTH SCHEMAS
// =====================================================================

export interface HealthResponse {
  /** Service health status ('healthy' or error string) */
  status: string;
  /** API semantic version (e.g. '1.0.0') */
  version: string;
}

// =====================================================================
// 2. RAG SERVICE SCHEMAS
// =====================================================================

export interface AskRequest {
  /** The enterprise policy query to answer strictly from knowledge base */
  question: string;
}

export interface CitationSource {
  /** Ranking position from hybrid retrieval / reranking (1-indexed) */
  rank: number;
  /** Document title extracted from markdown headers or metadata */
  title: string;
  /** Relative source file path (e.g. 'data/policies/travel_policy.md') */
  source_file: string;
  /** Unique chunk identifier (e.g. 'chunk_1', sha hash) */
  chunk_uid: string;
  /** Cross-encoder rerank relevance score */
  rerank_score: number;
  /** Passages / excerpt extracted from retrieved chunk */
  snippet: string;
}

export interface AskResponse {
  /** Original sanitized query */
  question: string;
  /** Grounded answer generated by LLM */
  answer: string;
  /** True if question was refused due to insufficient evidence */
  is_refusal: boolean;
  /** Verifiable deterministic source citations supporting answer */
  sources: CitationSource[];
}

// =====================================================================
// 3. STRUCTURED POSTGRESQL DATA SCHEMAS
// =====================================================================

export interface ManagerInfo {
  employee_id: string;
  name: string;
  email: string;
  job_title: string;
}

export interface EmployeeResponse {
  employee_id: string;
  name: string;
  email: string;
  department: string;
  job_title: string;
  created_at: string;
  manager?: ManagerInfo | null;
}

export interface LeaveBalanceItem {
  leave_type: string;
  total_days: number;
  used_days: number;
  remaining_days: number;
  updated_at: string;
}

export interface EmployeeLeaveResponse {
  employee_id: string;
  name: string;
  department: string;
  total_allocated_days: number;
  total_used_days: number;
  total_remaining_days: number;
  balances: LeaveBalanceItem[];
}

export interface TravelExpenseItem {
  id: number;
  expense_date: string;
  category: string;
  amount: number;
  currency: string;
  status: string;
  description: string;
  created_at: string;
}

export interface EmployeeTravelResponse {
  employee_id: string;
  name: string;
  department: string;
  total_claims: number;
  total_amount: number;
  approved_amount: number;
  submitted_amount: number;
  reimbursed_amount: number;
  by_category: Record<string, number>;
  expenses: TravelExpenseItem[];
}

// =====================================================================
// 4. CONVERSATIONAL AGENT SCHEMAS (LANGGRAPH + MULTI-AGENT)
// =====================================================================

export interface AgentChatRequest {
  /** Unique session thread identifier */
  session_id: string;
  /** User message or follow-up query */
  message: string;
}

export interface AgentStepResponse {
  /** Sequential step position (1-indexed) */
  step_number: number;
  /** Name of the invoked tool (e.g., 'get_employee_profile_tool') */
  tool_name: string;
  /** Validated tool arguments */
  tool_args: Record<string, unknown>;
  /** Structured tool output/result */
  tool_result: Record<string, unknown>;
  /** Execution status: 'success', 'error', 'rejected_duplicate' */
  status: string;
  /** Tool execution duration in milliseconds */
  duration_ms: number;
  /** Sanitized error message if failed */
  error?: string | null;
}

export interface AgentExecutionTraceResponse {
  session_id?: string | null;
  total_steps: number;
  total_duration_ms: number;
  used_rag: boolean;
  status: string;
  tools_invoked: string[];
}

export interface AgentChatResponse {
  session_id: string;
  query: string;
  answer: string;
  status: 'completed' | 'pending_approval' | 'max_steps_reached' | 'rejected' | 'error';
  steps: AgentStepResponse[];
  total_steps: number;
  duration_ms: number;
  used_rag: boolean;
  citations: CitationSource[];
  trace?: AgentExecutionTraceResponse | null;
}

export interface SessionClearResponse {
  session_id: string;
  status: 'cleared' | 'deleted';
  message: string;
}

// =====================================================================
// 5. HUMAN-IN-THE-LOOP APPROVAL SCHEMAS
// =====================================================================

export interface ApprovalDecisionRequest {
  /** Explicit human decision: 'approve' or 'reject' */
  decision: 'approve' | 'reject';
  /** Optional session identifier to verify approval ownership against */
  session_id?: string | null;
  /** Optional operator justification or review notes */
  notes?: string | null;
}

export interface ApprovalDecisionResponse {
  approval_id: string;
  decision: string;
  status: 'completed' | 'rejected' | 'error' | string;
  answer: string;
  duration_ms: number;
  trace?: AgentExecutionTraceResponse | null;
}

// =====================================================================
// 6. ERROR RESPONSE
// =====================================================================

export interface ApiErrorResponse {
  detail: string;
  error_type?: string;
  status_code?: number;
}
